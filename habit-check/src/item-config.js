export function slotOf(category) {
  return SLOTS[category] || DEFAULT_SLOT;
}

// 依頼名の頭（「家族のNISA（妻・…）」の「（」より前）で名前の表を引く
export function itemName(questTitle, stage, slot, rarity) {
  const key = Object.keys(ITEM_NAMES).find((k) => String(questTitle || "").startsWith(k));
  if (!key) return GENERIC[slot]?.[rarity - 1] || "ふしぎなアイテム";
  const names = ITEM_NAMES[key];
  return stage < names.length ? names[stage] : `${names.at(-1)}＋${stage - names.length + 1}`;
}

export function rarityOf(rank, stage, crit) {
  return Math.min(MAX_RARITY, (RANK_RARITY[rank] || 1) + stage + (crit ? 1 : 0));
}

// ほうこくのIDから会心かどうかを決める（同じほうこくはいつも同じ結果）
export function isCrit(reportId) {
  let h = 0;
  for (const c of String(reportId).replace(/-/g, "")) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return h % CRIT_EVERY === 0;
}
