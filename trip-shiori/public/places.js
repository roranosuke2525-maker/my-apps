function norm(s) {
  return String(s || "")
    .normalize("NFKC")
    .replace(/[\s・･:：!！?？“”"'’‘、。「」『』（）()\-〜~＆&]/gu, "")
    .replace(/齋/gu, "斎")
    .replace(/[\u3041-\u3096]/gu, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60)) // ひらがな → カタカナ
    .toLowerCase();
}

const AREA_BY_ID = {};
for (const [parkId, park] of Object.entries(PARKS)) {
  for (const a of park.areas) AREA_BY_ID[a.id] = { ...a, park: parkId };
}

const PLACE_INDEX = Object.entries(PLACE_LIST).flatMap(([areaId, names]) =>
  names.map((raw) => {
    const [name, mark = ""] = raw.split("|");
    const kind = { f: "food", s: "shop", B: "food", k: "baby" }[mark] || "ride";
    return { name, key: norm(name), area: areaId, park: AREA_BY_ID[areaId].park, kind, beer: mark === "B" };
  }));

// 文から施設を探す。①「（エリア名）」があればそのエリア ②施設名がまるごと入っている ③書いた文が施設名の一部（2文字以上）
function findPlace(text) {
  const t = norm(text.replace(/^\d{1,2}[:：]\d{2}/u, ""));
  if (t.length < 2) return null;
  const byArea = Object.values(AREA_BY_ID).find((a) => t.includes(norm(a.name)));
  const whole = PLACE_INDEX.filter((p) => t.includes(p.key)).sort((a, b) => b.key.length - a.key.length)[0];
  if (whole) return { name: whole.name, area: byArea?.id || whole.area };
  if (byArea) return { name: null, area: byArea.id };
  const part = PLACE_INDEX.find((p) => t.length >= 2 && p.key.includes(t));
  return part ? { name: part.name, area: part.area } : null;
}

window.TripPlaces = { PARKS, AREA_BY_ID, PLACE_INDEX, KINDS, findPlace, norm };
